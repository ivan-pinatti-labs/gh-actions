def test_refuses_a_changed_marker_as_a_different_package(
    tmp_path, monkeypatch, capsys, published
):
    before = HEADER + _entry("rich", "14.0.0", [1], "")
    after = HEADER + _entry("rich", '14.0.0 ; sys_platform == "linux"', [1], "")
    root, diff = _bump(tmp_path, before, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert 'adds package rich ; sys_platform == "linux"' in out
    assert "removes package rich," in out


@pytest.mark.parametrize(
    "after",
    [
        # An index option slipped in above the packages.
        HEAD.replace(HEADER, HEADER + "--extra-index-url https://example.test/\n"),
        # The recorded command changed.
        HEAD.replace("--exclude-newer=P7D ", ""),
        # The packages swapped places.
        HEADER
        + _entry("pytest", "9.2.0", [5], "")
        + _entry("iniconfig", "2.1.0", [1, 2], ""),
    ],
    ids=["option", "header", "order"],
)
def test_refuses_a_change_outside_versions_and_hashes(
    tmp_path, monkeypatch, capsys, published, after
):
    root, diff = _bump(tmp_path, BASE, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert "changes something other than a version, its hashes" in out
    assert published["calls"] == []


@pytest.mark.parametrize(
    ("after", "reason"),
    [
        (HEAD + "requests\n", "not pinned with `==` and hashes: requests"),
        (HEAD + "requests==2.32.0\n", "not pinned with `==` and hashes"),
        (HEAD + "requests>=2 \\\n    --hash=sha256:" + _hash(1) + "\n", "not pinned"),
        (
            HEAD + "requests==2.32.0 \\\n# sneaky\n    --hash=sha256:" + _hash(1),
            "a comment inside a continued line",
        ),
        (HEAD + "requests==2.32.0 \\\n", "the file ends inside a continued line"),
    ],
    ids=["unpinned", "unhashed", "range", "comment", "dangling"],
)
def test_refuses_a_file_that_is_not_a_lock(
    tmp_path, monkeypatch, capsys, published, after, reason
):
    root, diff = _bump(tmp_path, BASE, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert reason in out


def test_refuses_when_the_base_cannot_be_proven(
    tmp_path, monkeypatch, capsys, published
):
    # main has moved on since the branch: the checkout's copy is not the
    # diff's base, so neither side can be read whole.
    root, diff = _bump(tmp_path)
    (root / LOCK).write_text(BASE + "# edited on main since\n")

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert f"{LOCK}: its base on main could not be proven" in out
    assert published["calls"] == []


def test_a_path_outside_the_allowlist_is_never_looked_up(
    tmp_path, monkeypatch, capsys, published
):
    config = CONFIG.replace(f"  - {LOCK}\n", "")
    root = _repo(tmp_path, {LOCK: BASE}, config)

    code, out = _run(monkeypatch, capsys, root, _file_diff(LOCK, BASE, HEAD))

    assert code == 1
    assert f"{LOCK}: not a dependency pin file" in out
    assert published["calls"] == []


