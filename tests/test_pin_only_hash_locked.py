def test_refuses_a_hash_pypi_does_not_publish(tmp_path, monkeypatch, capsys, published):
    published[("pytest", "9.2.0")] = frozenset(_hash(n) for n in (5, 6))
    root, diff = _bump(tmp_path)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert "pytest==9.2.0 carries 1 hash(es) PyPI does not publish" in out
    assert _hash(7) in out


@pytest.mark.parametrize(
    "error", [OSError("network is unreachable"), ValueError("not JSON")]
)
def test_refuses_when_pypi_cannot_confirm(
    tmp_path, monkeypatch, capsys, published, error
):
    published[("pytest", "9.2.0")] = error
    root, diff = _bump(tmp_path)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert "could not confirm pytest==9.2.0's hashes with PyPI" in out
    assert str(error) in out


def test_refuses_an_added_package(tmp_path, monkeypatch, capsys, published):
    after = HEAD + _entry("pluggy", "1.6.0", [8], "    # via pytest\n")
    root, diff = _bump(tmp_path, BASE, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
    assert "adds package pluggy, which is not a version bump" in out
    assert published["calls"] == []


def test_refuses_a_removed_package(tmp_path, monkeypatch, capsys, published):
    after = HEADER + _entry("pytest", "9.2.0", [5], "")
    root, diff = _bump(tmp_path, BASE, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 1
