def test_accepts_a_bump_with_published_hashes(tmp_path, monkeypatch, capsys, published):
    published[("pytest", "9.2.0")] = frozenset(_hash(n) for n in (5, 6, 7, 8))
    source_before = "pytest==9.1.1\n"
    source_after = "pytest==9.2.0\n"
    root = _repo(tmp_path, {LOCK: BASE, SOURCE: source_before})
    diff = _file_diff(LOCK, BASE, HEAD) + _file_diff(
        SOURCE, source_before, source_after
    )

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 0, out
    # Only the package that moved is looked up; iniconfig is unchanged.
    assert published["calls"] == [("pytest", "9.2.0")]


def test_checks_hashes_that_changed_without_a_version_change(
    tmp_path, monkeypatch, capsys, published
):
    after = BASE.replace(f"sha256:{_hash(2)}", f"sha256:{_hash(9)}")
    published[("iniconfig", "2.1.0")] = frozenset({_hash(1), _hash(9)})
    root, diff = _bump(tmp_path, BASE, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 0, out
    assert published["calls"] == [("iniconfig", "2.1.0")]


def test_accepts_extras_and_markers_that_stay_put(
    tmp_path, monkeypatch, capsys, published
):
    marker = ' ; python_version >= "3.10"'
    before = HEADER + _entry("rich[jupyter]", "14.0.0" + marker, [1], "")
    after = HEADER + _entry("rich[jupyter]", "14.1.0" + marker, [2], "")
    published[("rich", "14.1.0")] = frozenset({_hash(2)})
    root, diff = _bump(tmp_path, before, after)

    code, out = _run(monkeypatch, capsys, root, diff)

    assert code == 0, out


