def test_no_hash_locked_paths_reads_nothing():
    assert pin_only._hash_locked_problems(["not a diff"], set()) == []


def test_is_hash_locked_needs_a_matching_rule():
    config = pin_only.Config(
        rules=(
            pin_only.PathRule(
                match="*requirements.txt",
                grammars=(pin_only.Grammar(pin_only.HASH_LOCKED),),
            ),
        )
    )
    assert pin_only._is_hash_locked("requirements.txt", config)
    assert not pin_only._is_hash_locked("Dockerfile", config)


@pytest.mark.parametrize(
    ("config", "message"),
    [
        (
            "allowed_paths: [a]\ndefault_grammars: [hash_locked_requirements]\n",
            "not in default_grammars",
        ),
        (
            "allowed_paths: [a]\nrules:\n  - path: a\n"
            "    grammars: [hash_locked_requirements, requirement_line]\n",
            "the only grammar of its rule",
        ),
        (
            "allowed_paths: [a]\nrules:\n  - path: a\n    raw: true\n"
            "    grammars: [hash_locked_requirements]\n",
            "without `raw` (a)",
        ),
    ],
    ids=["default", "shared", "raw"],
)
def test_configuration_keeps_the_grammar_alone(tmp_path, config, message):
    path = tmp_path / "pin-only.yml"
    path.write_text(config)
    with pytest.raises(SystemExit) as raised:
        pin_only.load_config(path, tmp_path)
    assert message in str(raised.value)


class _Response(io.BytesIO):
    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()


def test_pypi_lookup_reads_every_file_digest(monkeypatch):
    seen = {}

    def fake_urlopen(request, timeout):
        seen["url"] = request.full_url
        seen["timeout"] = timeout
        body = {"urls": [{"digests": {"sha256": "aa"}}, {"digests": {"sha256": "bb"}}]}
        return _Response(json.dumps(body).encode())

    monkeypatch.setattr(pin_only.urllib.request, "urlopen", fake_urlopen)

    assert pin_only._pypi_sha256s("zope.interface", "7.0+local") == {"aa", "bb"}
    assert seen == {
        "url": "https://pypi.org/pypi/zope.interface/7.0%2Blocal/json",
        "timeout": 30,
    }


@pytest.mark.parametrize(
    "body",
    [{"info": {}}, {"urls": [{"digests": {}}]}, {"urls": None}],
    ids=["no-urls", "no-sha256", "null"],
)
def test_pypi_lookup_refuses_an_unexpected_answer(monkeypatch, body):
    monkeypatch.setattr(
        pin_only.urllib.request,
        "urlopen",
        lambda request, timeout: _Response(json.dumps(body).encode()),
    )
    with pytest.raises(ValueError, match="unexpected answer from PyPI"):
        pin_only._pypi_sha256s("pytest", "9.2.0")
