"""Tests for `hash_locked_requirements`, the file level grammar.

They run in process rather than through the command line, because the one
thing this grammar does that no other does is ask PyPI, and the fetch has to
be stubbed: nothing in this suite touches the network. Every diff is still
built against a real base file with a real `index` line, since the grammar
reads both sides whole and refuses a file whose base it cannot prove.
"""

import difflib
import io
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

# E402: the import has to follow the sys.path line above.
import pin_only  # noqa: E402

LOCK = "tests/requirements.txt"
SOURCE = "tests/requirements.in"

CONFIG = f"""\
allowed_paths:
  - {LOCK}
  - {SOURCE}
rules:
  - path: "*requirements.txt"
    grammars: [hash_locked_requirements]
  - path: "*requirements.in"
    grammars: [requirement_line]
"""

HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    uv pip compile --generate-hashes --python-version=3.14 "
    "--exclude-newer=P7D --output-file=requirements.txt requirements.in\n"
)


def _hash(n: int) -> str:
    return f"{n:064x}"


def _entry(name: str, version: str, hashes: list[int], via: str) -> str:
    lines = [f"{name}=={version} \\"]
    lines += [f"    --hash=sha256:{_hash(n)} \\" for n in hashes[:-1]]
    lines.append(f"    --hash=sha256:{_hash(hashes[-1])}")
    return "\n".join(lines) + "\n" + via


BASE = (
    HEADER
    + _entry("iniconfig", "2.1.0", [1, 2], "    # via pytest\n")
    + _entry("pytest", "9.1.1", [3, 4], "    # via -r requirements.in\n")
)
HEAD = (
    HEADER
    + _entry("iniconfig", "2.1.0", [1, 2], "    # via pytest\n")
    + _entry(
        "pytest",
        "9.2.0",
        [5, 6, 7],
        "    # via\n    #   -r requirements.in\n",
    )
)


def _file_diff(path: str, before: str, after: str) -> str:
    """A `git diff` style section for one file, with the base's blob id."""
    old = pin_only._git_blob_id(before.encode())
    new = pin_only._git_blob_id(after.encode())
    body = difflib.unified_diff(
        before.splitlines(),
        after.splitlines(),
        f"a/{path}",
        f"b/{path}",
        lineterm="",
    )
    return (
        f"diff --git a/{path} b/{path}\n"
        f"index {old[:12]}..{new[:12]} 100644\n" + "\n".join(body) + "\n"
    )


def _repo(tmp_path: Path, files: dict[str, str], config: str = CONFIG) -> Path:
    (tmp_path / ".github").mkdir(exist_ok=True)
    (tmp_path / ".github" / "pin-only.yml").write_text(config)
    for path, text in files.items():
        target = tmp_path / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    return tmp_path


@pytest.fixture
def published(monkeypatch):
    """Stub PyPI with a table of release hashes, recording every query."""
    table: dict[tuple[str, str], object] = {}
    calls: list[tuple[str, str]] = []

    def fake(name: str, version: str) -> frozenset[str]:
        calls.append((name, version))
        answer = table.get((name, version), frozenset())
        if isinstance(answer, Exception):
            raise answer
        return answer

    monkeypatch.setattr(pin_only, "_pypi_sha256s", fake)
    table["calls"] = calls
    return table


def _run(monkeypatch, capsys, root: Path, diff: str) -> tuple[int, str]:
    monkeypatch.setattr(sys, "stdin", io.StringIO(diff))
    code = pin_only.main(["--repo-root", str(root)])
    return code, capsys.readouterr().out


def _bump(tmp_path, before=BASE, after=HEAD) -> tuple[Path, str]:
    root = _repo(tmp_path, {LOCK: before})
    return root, _file_diff(LOCK, before, after)


